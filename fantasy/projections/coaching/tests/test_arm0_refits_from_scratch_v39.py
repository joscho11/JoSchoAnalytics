class ExplodingEstimator:
    """Raises on ANY use. If a prediction ever came from the stored object, this detonates."""

    def __getattr__(self, name):
        raise AssertionError(f"the STORED estimator was used: .{name} accessed")

    def __call__(self, *a, **k):
        raise AssertionError("the STORED estimator was called")

    def __reduce__(self):
        return (ExplodingEstimator, ())


