# 2. `fit_predict` constructs a FRESH estimator every call
# =====================================================================================================
def test_fit_predict_constructs_a_fresh_estimator_each_call(monkeypatch):
    RB, _ = EX._production_engine()
    made = []
    real_make = RB._make_model

    def spy(family, params):
        m = real_make(family, params)
        made.append(m)          # hold the OBJECT: id() can be recycled once the first is freed,
        return m                # which made an `id` comparison flake in a full-suite run

    monkeypatch.setattr(RB, "_make_model", spy)
    rng = np.random.default_rng(0)
    feats = ["f1", "f2"]
    train = pd.DataFrame({"f1": rng.normal(size=40), "f2": rng.normal(size=40),
                          "y": rng.normal(size=40)})
    test = pd.DataFrame({"f1": rng.normal(size=10), "f2": rng.normal(size=10)})
    spec = {"family": "lightgbm", "params": {"num_leaves": 5, "n_estimators": 10}}

    p1 = EX.fit_predict(spec, train, test, feats)
    p2 = EX.fit_predict(spec, train, test, feats)
    assert len(made) == 2 and made[0] is not made[1], "the same estimator instance was reused"
    np.testing.assert_allclose(p1, p2, err_msg="a fresh fit on identical data must be reproducible")


def test_fit_predict_fits_on_the_frame_it_is_GIVEN(monkeypatch):
    """The fold's own training rows reach `.fit`, so a fold cannot inherit anything."""
    RB, _ = EX._production_engine()
    seen = {}
    real_make = RB._make_model

    def spy(family, params):
        m = real_make(family, params)
        real_fit = m.fit

        def fit(X, y, *a, **k):
            seen["n_rows"] = len(X)
            seen["y"] = np.asarray(y, float).copy()
            return real_fit(X, y, *a, **k)
        m.fit = fit
        return m

    monkeypatch.setattr(RB, "_make_model", spy)
    rng = np.random.default_rng(1)
    train = pd.DataFrame({"f1": rng.normal(size=25), "y": rng.normal(size=25)})
    test = pd.DataFrame({"f1": rng.normal(size=5)})
    EX.fit_predict({"family": "lightgbm", "params": {"num_leaves": 5, "n_estimators": 10}},
                   train, test, ["f1"])
    assert seen["n_rows"] == 25
    np.testing.assert_allclose(seen["y"], train["y"].to_numpy(float))


