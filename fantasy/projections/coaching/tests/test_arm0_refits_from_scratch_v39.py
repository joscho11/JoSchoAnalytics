def test_the_sentinel_really_does_explode():
    """Guard against a vacuous poisoning: the sentinel must be impossible to use."""
    e = ExplodingEstimator()
    with pytest.raises(AssertionError):
        e.fit
    with pytest.raises(AssertionError):
        e.predict
    with pytest.raises(AssertionError):
        e()
    # but reading its TYPE is safe, which is all `arm0_definition` does
    assert type(e).__name__ == "ExplodingEstimator"


