def test_POISONING_the_stored_estimator_cannot_change_a_single_prediction(poisoned_models,
                                                                          monkeypatch):
    """Run the full nested pipeline twice — canonical bundles, then poisoned — and compare.

    If any prediction came from the serialized estimator the poisoned run would raise; if any came
    from stale state the two runs would differ. Synthetic `y` throughout; no outcome is read.
    """
    panel, coach = _small_panel(), _coach_a()
    kwargs = dict(outer_seasons=[2019], positions=["RB"], bootstrap_draws=25, run_placebo=False,
                  verbose=False)

    EX.reset_pipeline_assertions()
    clean = EX.run_experiment(panel, coach, None, **kwargs)

    monkeypatch.setattr(EX, "MODELS", poisoned_models)
    # NON-VACUITY: prove the poisoned bundles are the ones this run reads. Without this, a test that
    # silently kept reading the canonical models would still pass and prove nothing.
    assert all(s["model_class"].endswith("ExplodingEstimator")
               for s in EX.arm0_definition().values()), "the poisoned models dir was not in use"

    EX.reset_pipeline_assertions()
    poisoned = EX.run_experiment(panel, coach, None, **kwargs)

    a = clean["metrics"].sort_values(list(clean["metrics"].columns)).reset_index(drop=True)
    b = poisoned["metrics"].sort_values(list(poisoned["metrics"].columns)).reset_index(drop=True)
    pd.testing.assert_frame_equal(a, b, check_exact=False, rtol=0, atol=0)

    sa = clean["selection"].reset_index(drop=True)
    sb = poisoned["selection"].reset_index(drop=True)
    pd.testing.assert_frame_equal(sa, sb, check_exact=False, rtol=0, atol=0)


