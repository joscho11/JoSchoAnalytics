def test_fold_training_frames_are_spied_and_carry_no_late_pff(monkeypatch, matrix):
    """End-to-end: intercept every `fit_predict` and assert each training frame is point-in-time."""
    pit = matrix[["player_id", "season"] + list(ARP.ROOKIE_MATRIX_PROVENANCE)]
    checked = {"frames": 0}
    real = EX.fit_predict

    def spy(spec, train, test, features):
        for frame in (train, test):
            if "player_id" not in frame.columns or "season" not in frame.columns:
                continue
            j = frame[["player_id", "season"]].merge(pit, on=["player_id", "season"], how="inner")
            for col in ARP.ROOKIE_MATRIX_PROVENANCE:
                nn = j[col].notna()
                if bool(nn.any()):
                    assert int((j.loc[nn, "season"] - j.loc[nn, col]).min()) >= 1
            checked["frames"] += 1
        return real(spec, train, test, features)

    monkeypatch.setattr(EX, "fit_predict", spy)
    EX.reset_pipeline_assertions()
    EX.run_experiment(_small_panel(), _coach_a(), None, outer_seasons=[2019], positions=["RB"],
                      bootstrap_draws=25, run_placebo=False, verbose=False)
    assert checked["frames"] > 0, "no fold frame was inspected; the spy never ran"


